QMimeData* GroupTreeModel::mimeData(const QModelIndexList& indexes) const
{
    QMimeData* mimeData = new QMimeData;
    QList<QUrl> urls;
    QSet<QString> seen;
    QByteArray encodedData;
    QDataStream stream(&encodedData, QIODevice::WriteOnly);

    for (const auto& index : indexes)
    {
        if (index.column() != 0)
            continue; // Only process first column

        if (isFrame(index))
        {
            FrameId id = getFrameId(index);
            if (id.isValid() && !seen.contains(id.canonicalPath()))
            {
                urls.append(QUrl::fromLocalFile(id.canonicalPath()));
                stream << id.canonicalPath();
                seen.insert(id.canonicalPath());
            }
        }
        else if (isGroup(index))
        {
            // Add all frames in group
            // We need to traverse children
            TreeDisplayNode* item = static_cast<TreeDisplayNode*>(index.internalPointer());
            // Recursive function to get all frame children
            const auto collectFrames = [&](auto&& self, TreeDisplayNode* node) -> void {
                if (node->type == TreeDisplayNode::Type::Frame && node->frameInfo.has_value())
                {
                    if (!seen.contains(node->frameInfo->id.canonicalPath()))
                    {
                        urls.append(QUrl::fromLocalFile(node->frameInfo->id.canonicalPath()));
                        stream << node->frameInfo->id.canonicalPath();
                        seen.insert(node->frameInfo->id.canonicalPath());
                    }
                }
                else
                {
                    for (const auto& child : node->children)
                    {
                        self(self, child.get());
                    }
                }
            };
            collectFrames(collectFrames, item);
        }
    }
    mimeData->setUrls(urls);
    mimeData->setData(QStringLiteral("application/x-afternight-frame-id"), encodedData);
    return mimeData;
}

