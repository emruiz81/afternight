void GroupTreeModel::onGroupingChanged(FrameType type)
{
    if (type != m_impl->frameType)
    {
        // Light diagnostics depend on Dark tolerance settings (e.g. temperature tolerance).
        if (m_impl->frameType == FrameType::Light && type == FrameType::Dark)
        {
            // setGroupingOptions emits calibrationChanged() immediately after groupingChanged().
            // Avoid rebuilding twice; we already rebuild here for Light diagnostics.
            m_impl->suppressNextCalibrationChanged = true;
            m_impl->invalidateWarningPaths();
            m_impl->rebuild();
            emit filterChanged();
        }
        return;
    }

    if (m_impl->suppressNextGroupingChanged)
    {
        m_impl->suppressNextGroupingChanged = false;
        return;
    }

    if (m_impl->frameType == FrameType::Light)
    {
        // Grouping changes are emitted together with calibrationChanged(); suppress the redundant rebuild.
        m_impl->suppressNextCalibrationChanged = true;
    }

    m_impl->rebuild();
    emit filterChanged();
}

void GroupTreeModel::onFramesAdded(FrameType type, const QStringList& paths)
{
    // Light diagnostics (calibration coverage) depend on calibration frame collections too.
    if (m_impl->frameType == FrameType::Light &&
        (type == FrameType::Bias || type == FrameType::Dark || type == FrameType::Flat) && type != m_impl->frameType)
    {
        m_impl->invalidateWarningPaths();
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    if (type != m_impl->frameType)
    {
        return;
    }

    if (m_impl->frameType == FrameType::Light && m_impl->showOnlyCalibrationWarnings)
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    const bool suppress = (m_impl->displayMode == DisplayMode::Flat);
    m_impl->suppressNextGroupingChanged = suppress;
    m_impl->suppressNextCalibrationChanged = suppress;

    if (m_impl->filter.has_value() && !m_impl->filter->isEmpty())
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    // Incremental updates are currently supported for Flat mode only.
    if (m_impl->displayMode != DisplayMode::Flat)
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    const auto& options = m_impl->dataModel->groupingOptions(m_impl->frameType);
    GroupingEngine groupingEngine;

    for (const auto& path : paths)
    {
        FrameId id(path);
        const auto frame_opt = m_impl->dataModel->frames(m_impl->frameType).findById(id);
        if (!frame_opt.has_value())
        {
            continue;
        }

        const FrameInfo frame = *frame_opt;
        const GroupKey group_key = frame.manualGroupKey.has_value()
                                       ? frame.manualGroupKey.value()
                                       : groupingEngine.computeGroupKey(frame, m_impl->frameType, options);
        const QString group_key_path = group_key.toString();
        const QString group_label = group_key.toCompactString();

        // Find or create group node (sorted by label for deterministic UI).
        TreeDisplayNode* group_node = nullptr;
        int group_row = -1;
        for (int i = 0; i < static_cast<int>(m_impl->root->children.size()); ++i)
        {
            TreeDisplayNode* node = m_impl->root->children[static_cast<size_t>(i)].get();
            if (node->type == TreeDisplayNode::Type::Group && node->keyPath == group_key_path)
            {
                group_node = node;
                group_row = i;
                break;
            }
        }

        if (!group_node)
        {
            auto new_group = std::make_unique<TreeDisplayNode>(TreeDisplayNode::Type::Group);
            new_group->label = group_label;
            new_group->keyPath = group_key_path;
            new_group->fullGroupKey = group_key;
            new_group->frameCount = 0;
            new_group->parent = m_impl->root.get();

            const auto sort_key = std::make_pair(group_label, group_key_path);
            auto it = std::lower_bound(
                m_impl->root->children.begin(), m_impl->root->children.end(), sort_key,
                [](const std::unique_ptr<TreeDisplayNode>& lhs, const std::pair<QString, QString>& rhs) {
                    if (!lhs)
                    {
                        return true;
                    }
                    if (lhs->label != rhs.first)
                    {
                        return lhs->label < rhs.first;
                    }
                    return lhs->keyPath < rhs.second;
                });
            group_row = static_cast<int>(std::distance(m_impl->root->children.begin(), it));

            beginInsertRows(QModelIndex(), group_row, group_row);
            m_impl->root->children.insert(it, std::move(new_group));
            endInsertRows();

            group_node = m_impl->root->children[static_cast<size_t>(group_row)].get();
        }

        const QModelIndex group_index = index(group_row, 0, QModelIndex());

        // Insert frame (sorted by canonical path for stability).
        const QString frame_key = frame.id.canonicalPath();
        int frame_row = 0;
        {
            auto& children = group_node->children;
            auto fit = std::lower_bound(children.begin(), children.end(), frame_key,
                                        [](const std::unique_ptr<TreeDisplayNode>& lhs, const QString& rhs) {
                                            return lhs && lhs->frameInfo.has_value() &&
                                                   lhs->frameInfo->id.canonicalPath() < rhs;
                                        });
            frame_row = static_cast<int>(std::distance(children.begin(), fit));

            auto new_frame = std::make_unique<TreeDisplayNode>(TreeDisplayNode::Type::Frame);
            new_frame->frameInfo = frame;
            new_frame->parent = group_node;
            m_impl->frameNodeByPath.insert(frame_key, new_frame.get());

            beginInsertRows(group_index, frame_row, frame_row);
            children.insert(fit, std::move(new_frame));
            endInsertRows();
        }

        group_node->frameCount = static_cast<int>(group_node->children.size());
        emit dataChanged(group_index, group_index, {Qt::DisplayRole});
    }

    m_impl->invalidateWarningPaths();
    m_impl->refreshWarningPathsIfNeeded();

    m_impl->totalCount = static_cast<int>(m_impl->dataModel->frames(m_impl->frameType).size());
    m_impl->matchCount = m_impl->totalCount;
    emit filterChanged();
}

void GroupTreeModel::onFramesRemoved(FrameType type, const QStringList& paths)
{
    // Light diagnostics (calibration coverage) depend on calibration frame collections too.
    if (m_impl->frameType == FrameType::Light &&
        (type == FrameType::Bias || type == FrameType::Dark || type == FrameType::Flat) && type != m_impl->frameType)
    {
        m_impl->invalidateWarningPaths();
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    if (type != m_impl->frameType)
    {
        return;
    }

    if (m_impl->frameType == FrameType::Light && m_impl->showOnlyCalibrationWarnings)
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    const bool suppress = (m_impl->displayMode == DisplayMode::Flat);
    m_impl->suppressNextGroupingChanged = suppress;
    m_impl->suppressNextCalibrationChanged = suppress;

    if (m_impl->filter.has_value() && !m_impl->filter->isEmpty())
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    if (m_impl->displayMode != DisplayMode::Flat)
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    constexpr int kMaxIncrementalRemovals = 32;
    if (paths.size() > kMaxIncrementalRemovals)
    {
        m_impl->rebuild();
        emit filterChanged();
        return;
    }

    for (const auto& path : paths)
    {
        const QString canonical = FrameId(path).canonicalPath();
        const QModelIndex frame_index = findIndexForPath(canonical);
        if (!frame_index.isValid())
        {
            continue;
        }

        TreeDisplayNode* frame_node = static_cast<TreeDisplayNode*>(frame_index.internalPointer());
        TreeDisplayNode* group_node = frame_node ? frame_node->parent : nullptr;
        if (!group_node)
        {
            continue;
        }

        const QModelIndex group_index = parent(frame_index);

        auto& children = group_node->children;
        auto it = std::find_if(children.begin(), children.end(),
                               [&](const std::unique_ptr<TreeDisplayNode>& ptr) { return ptr.get() == frame_node; });
        if (it == children.end())
        {
            continue;
        }

        m_impl->frameNodeByPath.remove(canonical);

        const int row = static_cast<int>(std::distance(children.begin(), it));
        beginRemoveRows(group_index, row, row);
        children.erase(it);
        endRemoveRows();

        group_node->frameCount = static_cast<int>(children.size());
        emit dataChanged(group_index, group_index, {Qt::DisplayRole});

        if (children.empty())
        {
            // Remove empty group.
            auto& groups = m_impl->root->children;
            auto git = std::find_if(groups.begin(), groups.end(), [&](const std::unique_ptr<TreeDisplayNode>& ptr) {
                return ptr.get() == group_node;
            });
            if (git != groups.end())
            {
                const int group_row = static_cast<int>(std::distance(groups.begin(), git));
                beginRemoveRows(QModelIndex(), group_row, group_row);
                groups.erase(git);
                endRemoveRows();
            }
        }
    }

    m_impl->invalidateWarningPaths();
    m_impl->refreshWarningPathsIfNeeded();

    m_impl->totalCount = static_cast<int>(m_impl->dataModel->frames(m_impl->frameType).size());
    m_impl->matchCount = m_impl->totalCount;
    emit filterChanged();
}

void GroupTreeModel::onFrameUpdated(const QString& path)
{
    const QString canonical = FrameId(path).canonicalPath();
    if (m_impl->suppressNextFrameUpdated && canonical == m_impl->suppressNextFrameUpdatedPath)
    {
        m_impl->suppressNextFrameUpdated = false;
        m_impl->suppressNextFrameUpdatedPath.clear();
        return;
    }

    // Updates may move frames between groups; keep this simple/robust for now.
    m_impl->rebuild();
    emit filterChanged();
}
