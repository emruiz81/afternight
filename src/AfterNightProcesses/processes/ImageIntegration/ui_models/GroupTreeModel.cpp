class GroupTreeModel::Impl
{
public:
    Impl(GroupTreeModel* parent, FrameType type, IntegrationDataModel* model, QUndoStack* undo)
        : q(parent), frameType(type), dataModel(model), undoStack(undo)
    {
        // Initial empty root
        root = std::make_unique<TreeDisplayNode>(TreeDisplayNode::Type::Group);
        root->label = QStringLiteral("Root");
    }

    GroupTreeModel* q;
    FrameType frameType;
    IntegrationDataModel* dataModel;
    QUndoStack* undoStack = nullptr;
    DisplayMode displayMode = DisplayMode::Flat;
    std::unique_ptr<TreeDisplayNode> root;
    QHash<QString, TreeDisplayNode*> frameNodeByPath;
    QSet<QString> warningFramePaths;
    QSet<QString> calibrationWarningPaths;
    QSet<QString> temperatureWarningPaths;
    struct LightTempSpreadInfo
    {
        double minC = 0.0;
        double maxC = 0.0;
        double spreadC = 0.0;
        int sampleCount = 0;
    };
    QHash<GroupKey, LightTempSpreadInfo> lightTempSpreadWarnings;
    bool warningPathsDirty = true;
    bool suppressNextGroupingChanged = false;
    bool suppressNextCalibrationChanged = false;
    bool suppressNextFrameUpdated = false;
    QString suppressNextFrameUpdatedPath;

    std::optional<FrameTreeFilter> filter;
    bool showOnlyCalibrationWarnings = false;
    int matchCount = 0;
    int totalCount = 0;

    void rebuildFrameIndex()
    {
        frameNodeByPath.clear();
        if (!root)
        {
            return;
        }

        const auto indexRecursive = [&](auto&& self, TreeDisplayNode* node) -> void {
            if (!node)
            {
                return;
            }

            if (node->type == TreeDisplayNode::Type::Frame && node->frameInfo.has_value())
            {
                frameNodeByPath.insert(node->frameInfo->id.canonicalPath(), node);
            }

            for (const auto& child : node->children)
            {
                self(self, child.get());
            }
        };

        indexRecursive(indexRecursive, root.get());
    }

    void invalidateWarningPaths()
    {
        warningPathsDirty = true;
    }

    void refreshWarningPathsIfNeeded()
    {
        if (!warningPathsDirty || frameType != FrameType::Light)
        {
            return;
        }
        calibrationWarningPaths = computeWarningPaths(*dataModel);
        temperatureWarningPaths.clear();
        lightTempSpreadWarnings.clear();
        warningFramePaths = calibrationWarningPaths;
        warningPathsDirty = false;
    }

    void rebuild()
    {
        q->beginResetModel();

        // Get base groups from model.
        GroupedFrameView groups = (frameType == FrameType::Bias)   ? dataModel->biasGroups()
                                  : (frameType == FrameType::Dark) ? dataModel->darkGroups()
                                  : (frameType == FrameType::Flat) ? dataModel->flatGroups()
                                                                   : dataModel->lightGroups();

        const auto& options = dataModel->groupingOptions(frameType);

        // Merge excluded frames for UI display.
        groups = mergeExcludedFrames(std::move(groups), dataModel->frames(frameType), frameType, options);

        totalCount = static_cast<int>(dataModel->frames(frameType).size());
        matchCount = totalCount;

        // Always compute calibration warning paths for lights; used by coverage mode.
        if (frameType == FrameType::Light)
        {
            calibrationWarningPaths = computeWarningPaths(*dataModel);
        }

        if (filter.has_value() && !filter->isEmpty())
        {
            GroupedFrameView filtered;
            filtered.reserve(groups.size());

            matchCount = 0;
            for (const auto& group : groups)
            {
                std::vector<FrameInfo> filteredFrames;
                filteredFrames.reserve(group.frames.size());
                for (const auto& frame : group.frames)
                {
                    if (filter->matches(frame))
                    {
                        filteredFrames.push_back(frame);
                    }
                }

                if (!filteredFrames.empty())
                {
                    matchCount += static_cast<int>(filteredFrames.size());
                    filtered.push_back(GroupedFrameSet{group.key, std::move(filteredFrames)});
                }
            }

            groups = std::move(filtered);
        }

        if (frameType == FrameType::Light && showOnlyCalibrationWarnings)
        {
            const bool hasCalibrationFrames = !dataModel->biasFrames().empty() || !dataModel->darkFrames().empty() ||
                                              !dataModel->flatFrames().empty();

            if (!hasCalibrationFrames)
            {
                groups.clear();
                matchCount = 0;
                // Keep groups empty; rebuild proceeds so the view clears.
            }

            if (hasCalibrationFrames)
            {
                GroupedFrameView coverageGroups;
                coverageGroups.reserve(groups.size());
                int coverageCount = 0;

                for (const auto& group : groups)
                {
                    std::vector<FrameInfo> filteredFrames;
                    filteredFrames.reserve(group.frames.size());
                    for (const auto& frame : group.frames)
                    {
                        if (frame.excluded)
                        {
                            continue;
                        }
                        if (calibrationWarningPaths.contains(frame.id.canonicalPath()))
                        {
                            filteredFrames.push_back(frame);
                        }
                    }

                    if (!filteredFrames.empty())
                    {
                        coverageCount += static_cast<int>(filteredFrames.size());
                        coverageGroups.push_back(GroupedFrameSet{group.key, std::move(filteredFrames)});
                    }
                }

                groups = std::move(coverageGroups);
                matchCount = coverageCount;
            }
        }

        // Compute warnings after filtering so diagnostics match what's visible.
        if (frameType == FrameType::Light)
        {
            temperatureWarningPaths.clear();
            lightTempSpreadWarnings.clear();

            const double tolC = dataModel->groupingOptions(FrameType::Dark).temperatureToleranceC;
            if (tolC > 0.0)
            {
                for (const auto& group : groups)
                {
                    std::vector<double> temps;
                    temps.reserve(group.frames.size());
                    for (const auto& frame : group.frames)
                    {
                        if (frame.excluded)
                        {
                            continue;
                        }
                        const auto t = frame.metadata.temperatureC();
                        if (t.has_value())
                        {
                            temps.push_back(*t);
                        }
                    }

                    if (temps.size() < 2)
                    {
                        continue;
                    }

                    const auto [itMin, itMax] = std::minmax_element(temps.begin(), temps.end());
                    const double minC = *itMin;
                    const double maxC = *itMax;
                    const double spreadC = maxC - minC;
                    if (spreadC <= tolC)
                    {
                        continue;
                    }

                    lightTempSpreadWarnings.insert(
                        group.key, LightTempSpreadInfo{minC, maxC, spreadC, static_cast<int>(temps.size())});
                    for (const auto& frame : group.frames)
                    {
                        if (!frame.excluded)
                        {
                            temperatureWarningPaths.insert(frame.id.canonicalPath());
                        }
                    }
                }
            }

            warningFramePaths = calibrationWarningPaths;
            warningFramePaths.unite(temperatureWarningPaths);
            warningPathsDirty = false;
        }

        FrameTreeBuilder::DisplayMode builderMode = (displayMode == DisplayMode::Flat)
                                                        ? FrameTreeBuilder::DisplayMode::Flat
                                                        : FrameTreeBuilder::DisplayMode::Hierarchical;

        root = FrameTreeBuilder::buildTree(groups, options, builderMode, frameType);
        rebuildFrameIndex();

        // Refresh warning paths if dirty (only for Light frames).
        refreshWarningPathsIfNeeded();

        q->endResetModel();
    }
};

GroupTreeModel::GroupTreeModel(FrameType type, IntegrationDataModel* dataModel, QObject* parent, QUndoStack* undoStack)
    : QAbstractItemModel(parent), m_impl(std::make_unique<Impl>(this, type, dataModel, undoStack))
{
    connect(dataModel, &IntegrationDataModel::modelReset, this, &GroupTreeModel::onModelReset);
    connect(dataModel, &IntegrationDataModel::groupingChanged, this, &GroupTreeModel::onGroupingChanged);
    connect(dataModel, &IntegrationDataModel::framesAdded, this, &GroupTreeModel::onFramesAdded);
    connect(dataModel, &IntegrationDataModel::framesRemoved, this, &GroupTreeModel::onFramesRemoved);
    connect(dataModel, &IntegrationDataModel::frameUpdated, this, &GroupTreeModel::onFrameUpdated);

    // Invalidate warning paths cache when calibration state changes.
    connect(dataModel, &IntegrationDataModel::calibrationChanged, this, [this](FrameType type) {
        if (m_impl->frameType != FrameType::Light)
        {
            return;
        }

        if (m_impl->suppressNextCalibrationChanged)
        {
            m_impl->suppressNextCalibrationChanged = false;
            return;
        }

        // Calibration changes can affect warning highlights.
        m_impl->invalidateWarningPaths();
        m_impl->rebuild();
        emit filterChanged();
    });

    // Initial build
    m_impl->rebuild();
}

void GroupTreeModel::setFramesExcluded(const QStringList& paths, bool excluded)
{
    if (!m_impl || !m_impl->dataModel || paths.isEmpty())
    {
        return;
    }

    // Keep this model stable for bulk include/exclude: excluded does not change group membership,
    // and rebuilding would invalidate indexes (tests and selection propagation rely on stable indexes).
    bool anyChanged = false;
    QSet<QPersistentModelIndex> touchedGroups;
    QStringList changedPaths;
    changedPaths.reserve(paths.size());

    for (const auto& rawPath : paths)
    {
        if (rawPath.trimmed().isEmpty())
        {
            continue;
        }

        const QString canonical = FrameId(rawPath).canonicalPath();
        const QModelIndex idx = findIndexForPath(canonical);
        if (!idx.isValid())
        {
            continue;
        }

        TreeDisplayNode* node = static_cast<TreeDisplayNode*>(idx.internalPointer());
        if (!node || node->type != TreeDisplayNode::Type::Frame || !node->frameInfo.has_value())
        {
            continue;
        }

        if (node->frameInfo->excluded == excluded)
        {
            continue;
        }

        anyChanged = true;

        node->frameInfo->excluded = excluded;
        changedPaths << canonical;

        const QModelIndex left = idx.sibling(idx.row(), 0);
        const QModelIndex right = idx.sibling(idx.row(), ColCount - 1);
        emit dataChanged(left, right,
                         {Qt::CheckStateRole, Qt::DisplayRole, Qt::DecorationRole, Qt::ToolTipRole, Qt::ForegroundRole,
                          Qt::BackgroundRole, Qt::FontRole});

        const QModelIndex groupIndex = parent(idx);
        if (groupIndex.isValid())
        {
            touchedGroups.insert(QPersistentModelIndex(groupIndex));
        }
    }

    if (!anyChanged)
    {
        return;
    }

    // Update the backing model once, coalescing expensive recomputations.
    // Excluded does not change group membership; suppress the resulting regroup/calibration signals for this view.
    m_impl->suppressNextGroupingChanged = true;
    m_impl->suppressNextCalibrationChanged = true;
    if (m_impl->undoStack)
    {
        std::vector<FrameAttributeChange> changes;
        changes.reserve(changedPaths.size());
        for (const auto& changedPath : changedPaths)
        {
            changes.push_back(FrameAttributeChange{changedPath, !excluded, excluded});
        }
        m_impl->undoStack->push(
            new SetFrameAttributesCommand(m_impl->dataModel, FrameAttribute::Excluded, std::move(changes)));
    }
    else
    {
        m_impl->dataModel->setFramesExcluded(m_impl->frameType, changedPaths, excluded);
    }

    if (m_impl->frameType == FrameType::Light)
    {
        m_impl->invalidateWarningPaths();
        m_impl->refreshWarningPathsIfNeeded();
    }

    for (const auto& groupIdx : touchedGroups)
    {
        if (!groupIdx.isValid())
        {
            continue;
        }

        emit dataChanged(groupIdx, groupIdx.sibling(groupIdx.row(), ColCount - 1),
                         {Qt::DisplayRole, Qt::ToolTipRole, Qt::ForegroundRole, Qt::BackgroundRole, Qt::FontRole});
    }
}

void GroupTreeModel::moveFramesToGroup(const QStringList& paths, const QString& targetObject,
                                       const QString& targetSession, const GroupingOptions& groupingOptions)
{
    if (!m_impl || !m_impl->dataModel)
    {
        return;
    }

    if (paths.isEmpty())
    {
        return;
    }

    const auto& collection = m_impl->dataModel->frames(m_impl->frameType);

    std::vector<FrameAttributeChange> objectChanges;
    std::vector<FrameAttributeChange> sessionChanges;
    objectChanges.reserve(static_cast<size_t>(paths.size()));
    sessionChanges.reserve(static_cast<size_t>(paths.size()));

    for (const QString& path : paths)
    {
        const FrameId id(path);
        const auto frameOpt = collection.findById(id);
        if (!frameOpt.has_value())
        {
            continue;
        }

        if (groupingOptions.byObject && frameOpt->effectiveObjectName() != targetObject)
        {
            objectChanges.push_back(FrameAttributeChange{path, frameOpt->userObjectName, targetObject});
        }

        if (groupingOptions.bySession && frameOpt->effectiveSession() != targetSession)
        {
            sessionChanges.push_back(FrameAttributeChange{path, frameOpt->userSession, targetSession});
        }
    }

    if (objectChanges.empty() && sessionChanges.empty())
    {
        return;
    }

    if (m_impl->undoStack)
    {
        m_impl->undoStack->beginMacro(tr("Move frames to group"));
        if (!objectChanges.empty())
        {
            m_impl->undoStack->push(new SetFrameAttributesCommand(m_impl->dataModel, FrameAttribute::UserObjectName,
                                                                  std::move(objectChanges)));
        }
        if (!sessionChanges.empty())
        {
            m_impl->undoStack->push(new SetFrameAttributesCommand(m_impl->dataModel, FrameAttribute::UserSession,
                                                                  std::move(sessionChanges)));
        }
        m_impl->undoStack->endMacro();
        return;
    }

    // Fallback: keep behavior for contexts without undo.
    m_impl->dataModel->beginBatchUpdate();
    for (const auto& ch : objectChanges)
    {
        m_impl->dataModel->updateFrameAttribute(ch.path, FrameAttribute::UserObjectName, ch.newValue);
    }
    for (const auto& ch : sessionChanges)
    {
        m_impl->dataModel->updateFrameAttribute(ch.path, FrameAttribute::UserSession, ch.newValue);
    }
    m_impl->dataModel->endBatchUpdate();
}

GroupTreeModel::~GroupTreeModel()
{
    QCoreApplication::removePostedEvents(this, QEvent::MetaCall);
}

QModelIndex GroupTreeModel::index(int row, int column, const QModelIndex& parent) const
{
    if (!hasIndex(row, column, parent))
        return QModelIndex();

    TreeDisplayNode* parentItem =
        parent.isValid() ? static_cast<TreeDisplayNode*>(parent.internalPointer()) : m_impl->root.get();

    if (row < static_cast<int>(parentItem->children.size()))
        return createIndex(row, column, parentItem->children[row].get());

    return QModelIndex();
}

QModelIndex GroupTreeModel::parent(const QModelIndex& child) const
{
    if (!child.isValid())
        return QModelIndex();

    TreeDisplayNode* childItem = static_cast<TreeDisplayNode*>(child.internalPointer());
    TreeDisplayNode* parentItem = childItem->parent;

    if (!parentItem || parentItem == m_impl->root.get())
        return QModelIndex();

    // We need to find the row of parentItem in ITS parent
    TreeDisplayNode* grandParent = parentItem->parent;
    if (!grandParent)
        return QModelIndex(); // Should not happen if parentItem is not root

    auto it = std::find_if(grandParent->children.begin(), grandParent->children.end(),
                           [&](const std::unique_ptr<TreeDisplayNode>& ptr) { return ptr.get() == parentItem; });

    if (it == grandParent->children.end())
        return QModelIndex(); // Should not happen

    int row = static_cast<int>(std::distance(grandParent->children.begin(), it));
    return createIndex(row, 0, parentItem);
}

int GroupTreeModel::rowCount(const QModelIndex& parent) const
{
    if (parent.column() > 0)
        return 0;

    TreeDisplayNode* parentItem =
        parent.isValid() ? static_cast<TreeDisplayNode*>(parent.internalPointer()) : m_impl->root.get();
    return static_cast<int>(parentItem->children.size());
}

int GroupTreeModel::columnCount(const QModelIndex& parent) const
{
    return ColCount;
}

QVariant GroupTreeModel::data(const QModelIndex& index, int role) const
{
    if (!index.isValid())
        return QVariant();

    TreeDisplayNode* item = static_cast<TreeDisplayNode*>(index.internalPointer());

    if (role == Qt::DisplayRole)
    {
        if (item->type == TreeDisplayNode::Type::Group)
        {
            if (index.column() == ColName)
            {
                if (item->frameCount > 0)
                    return QStringLiteral("%1 (%2)").arg(item->label).arg(item->frameCount);
                else
                    return item->label;
            }
            // For other columns, groups are usually empty,
            // unless we want to show aggregates (future enhancement)
        }
        else if (item->type == TreeDisplayNode::Type::Frame && item->frameInfo.has_value())
        {
            const auto& frame = item->frameInfo.value();
            const auto& meta = frame.metadata;
            // Access grouping options to determine visibility logic (hide if grouped)
            const auto& options = m_impl->dataModel->groupingOptions(m_impl->frameType);

            switch (index.column())
            {
            case ColName:
                return QFileInfo(frame.displayPath).fileName();
            case ColResolution:
                return options.byResolution ? QVariant() : meta.resolutionString();
            case ColFilter:
                return options.byFilter ? QVariant() : meta.filter();
            case ColObject:
                return options.byObject ? QVariant() : frame.effectiveObjectName();
            case ColSession:
                return options.bySession ? QVariant() : frame.effectiveSession();
            case ColISO:
                return options.byIsoGain ? QVariant()
                                         : (meta.isoGain().has_value() ? QString::number(meta.isoGain().value())
                                                                       : QStringLiteral("-"));
            case ColExposure:
                return options.byExposure ? QVariant()
                                          : (QString::number(meta.exposureSeconds(), 'f', 1) + QStringLiteral("s"));
            case ColTag:
                return options.byCustomTag ? QVariant() : frame.customTag;
            }
        }
    }

    if (role == Qt::ToolTipRole)
    {
        if (item->type == TreeDisplayNode::Type::Group && index.column() == ColName)
        {
            QString tooltip = item->label;

            int included = 0;
            int excluded = 0;
            countFramesRecursive(item, included, excluded);
            tooltip += QStringLiteral("\n") + tr("Frames: %1 included, %2 excluded").arg(included).arg(excluded);

            if (item->fullGroupKey.has_value())
            {
                tooltip += QStringLiteral("\n") + tr("Key: %1").arg(item->fullGroupKey->toCompactString());
            }

            if (m_impl->frameType == FrameType::Light)
            {
                const bool hasCalibrationWarnings = nodeHasWarning(item, m_impl->calibrationWarningPaths);
                const bool hasTempWarnings = nodeHasWarning(item, m_impl->temperatureWarningPaths);

                if (hasCalibrationWarnings || hasTempWarnings)
                {
                    tooltip += QStringLiteral("\n\n") + tr("Warnings:");
                    if (hasCalibrationWarnings)
                    {
                        tooltip +=
                            QStringLiteral("\n") +
                            tr("- Some frames appear to be missing calibration matches (check Calibration tab).");
                    }
                    if (hasTempWarnings)
                    {
                        tooltip += QStringLiteral("\n") + tr("- Wide temperature spread in this group.");
                    }
                }

                if (item->fullGroupKey.has_value())
                {
                    const auto it = m_impl->lightTempSpreadWarnings.constFind(*item->fullGroupKey);
                    if (it != m_impl->lightTempSpreadWarnings.constEnd())
                    {
                        tooltip += QStringLiteral("\n\n") + tr("Temperature spread: %1C (min %2C, max %3C)")
                                                                .arg(QString::number(it->spreadC, 'f', 1),
                                                                     QString::number(it->minC, 'f', 1),
                                                                     QString::number(it->maxC, 'f', 1));
                        tooltip += QStringLiteral("\n") + tr("Tip: Match darks by temperature (or tighten dark "
                                                             "temperature tolerance) to reduce calibration mismatch.");
                    }
                }
            }

            return tooltip;
        }

        if (item->type == TreeDisplayNode::Type::Frame && index.column() == ColName && item->frameInfo.has_value())
        {
            const auto& frame = item->frameInfo.value();
            QString tooltip = frame.displayPath;

            if (m_impl->dataModel && m_impl->dataModel->isMasterFrame(frame.id))
            {
                const MasterSource source = m_impl->dataModel->masterSource(frame.id).value_or(MasterSource::Unknown);
                tooltip += QStringLiteral("\n\n") + tr("Master Frame") + QStringLiteral("\n") +
                           tr("Master Type: %1").arg(masterSourceToString(source));
            }

            // Add registration reference explanation if this frame has the diamond icon
            if (m_impl->frameType == FrameType::Light)
            {
                const QString canonical = frame.id.canonicalPath();
                const bool hasCalibrationWarnings = m_impl->calibrationWarningPaths.contains(canonical);
                const bool hasTempWarnings = m_impl->temperatureWarningPaths.contains(canonical);

                const RegistrationGroupKey regKey = RegistrationGroupKey::fromFrame(frame);
                const auto refId = m_impl->dataModel->registrationReferenceFrame(regKey);
                if (refId.has_value() && *refId == frame.id)
                {
                    tooltip += QStringLiteral("\n\n") + tr("Registration Reference Frame") + QStringLiteral("\n") +
                               tr("All frames in the same registration group (same dimensions, channels, "
                                  "and binning) will be aligned to this frame during registration.") +
                               QStringLiteral("\n\n") +
                               tr("Note: A registration group may contain multiple stacking groups "
                                  "(e.g., different filters or sessions). This reference is used "
                                  "only for alignment, not for normalization.");
                }

                if (hasCalibrationWarnings || hasTempWarnings)
                {
                    tooltip += QStringLiteral("\n\n") + tr("Warnings:");
                    if (hasCalibrationWarnings)
                    {
                        tooltip += QStringLiteral("\n") + tr("- Missing calibration match (see Calibration tab).");
                    }
                    if (hasTempWarnings)
                    {
                        tooltip += QStringLiteral("\n") + tr("- Wide temperature spread in this group.");
                    }
                }
            }
            return tooltip;
        }
    }

    if (role == Qt::CheckStateRole)
    {
        if (item->type == TreeDisplayNode::Type::Frame && index.column() == ColName && item->frameInfo.has_value())
        {
            return item->frameInfo->excluded ? Qt::Unchecked : Qt::Checked;
        }
    }

    if (role == Qt::DecorationRole)
    {
        if (item->type == TreeDisplayNode::Type::Frame && index.column() == ColName && item->frameInfo.has_value())
        {
            const auto& frame = item->frameInfo.value();
            constexpr QSize kSmallDecorIconSize(14, 14);
            const bool is_warning = m_impl->warningFramePaths.contains(frame.id.canonicalPath());

            // Gold star for master frames (calibration types only)
            if (m_impl->frameType != FrameType::Light && m_impl->dataModel &&
                m_impl->dataModel->isMasterFrame(frame.id))
            {
                return coloredSvgPixmapOrFallback(QStringLiteral(":/AfterNight/icons/SVG/star_filled.svg"),
                                                  kSmallDecorIconSize, an::ui::tokens().colors.statusWarning);
            }

            // Diamond for registration reference frames (lights only)
            if (m_impl->frameType == FrameType::Light)
            {
                if (is_warning)
                {
                    return coloredSvgPixmapOrFallback(QStringLiteral(":/AfterNight/icons/SVG/warning.svg"),
                                                      kSmallDecorIconSize, statusAmber());
                }

                const RegistrationGroupKey regKey = RegistrationGroupKey::fromFrame(frame);
                const auto refId = m_impl->dataModel->registrationReferenceFrame(regKey);
                if (refId.has_value() && *refId == frame.id)
                {
                    return appIcon(QStringLiteral("diamond")).pixmap(kSmallDecorIconSize);
                }
            }
        }
    }

    // Row highlighting based on status (master/excluded/warning).
    if (role == Qt::ForegroundRole || role == Qt::BackgroundRole || role == Qt::FontRole)
    {
        if (item->type == TreeDisplayNode::Type::Frame && item->frameInfo.has_value())
        {
            const auto& frame = item->frameInfo.value();
            const bool is_excluded = frame.excluded;
            const bool is_master = m_impl->dataModel && m_impl->dataModel->isMasterFrame(frame.id);
            const bool is_warning = m_impl->warningFramePaths.contains(frame.id.canonicalPath());

            if (role == Qt::FontRole)
            {
                QFont font;
                if (is_master)
                {
                    font.setBold(true);
                }
                if (is_excluded)
                {
                    font.setStrikeOut(true);
                }
                return font;
            }

            if (role == Qt::ForegroundRole)
            {
                if (is_excluded)
                {
                    return resolvedRowHighlightTextColor(translucent(statusGray(), 35), statusGray());
                }
                if (is_warning)
                {
                    const QColor preferred =
                        index.column() == ColName ? statusAmber() : an::ui::tokens().colors.textPrimary;
                    return resolvedRowHighlightTextColor(translucent(statusAmber(), 30), preferred);
                }
            }

            if (role == Qt::BackgroundRole)
            {
                if (is_excluded)
                {
                    return translucent(statusGray(), 35);
                }
                if (is_warning)
                {
                    return translucent(statusAmber(), 30);
                }
            }
        }
        else if (item->type == TreeDisplayNode::Type::Group)
        {
            if (role == Qt::ForegroundRole && !m_impl->warningFramePaths.isEmpty() &&
                m_impl->frameType == FrameType::Light)
            {
                if (nodeHasWarning(item, m_impl->warningFramePaths))
                {
                    return resolvedRowHighlightTextColor(translucent(statusAmber(), 18),
                                                         an::ui::tokens().colors.textPrimary);
                }
            }
            if (role == Qt::BackgroundRole && !m_impl->warningFramePaths.isEmpty() &&
                m_impl->frameType == FrameType::Light)
            {
                if (nodeHasWarning(item, m_impl->warningFramePaths))
                {
                    return translucent(statusAmber(), 18);
                }
            }
        }
    }

    return QVariant();
}

bool GroupTreeModel::setData(const QModelIndex& index, const QVariant& value, int role)
{
    if (!index.isValid())
        return false;

    if (role == Qt::EditRole)
    {
        TreeDisplayNode* item = static_cast<TreeDisplayNode*>(index.internalPointer());
        if (item->type == TreeDisplayNode::Type::Frame && item->frameInfo.has_value() && m_impl->dataModel)
        {
            const QString canonicalPath = item->frameInfo->id.canonicalPath();
            const QString text = value.toString().trimmed();

            switch (index.column())
            {
            case ColSession:
                if (m_impl->undoStack)
                {
                    const QString oldText = item->frameInfo->userSession;
                    if (oldText != text)
                    {
                        m_impl->undoStack->push(new SetFrameAttributesCommand(
                            m_impl->dataModel, FrameAttribute::UserSession, {{canonicalPath, oldText, text}}));
                    }
                }
                else
                {
                    m_impl->dataModel->updateFrameAttribute(canonicalPath, FrameAttribute::UserSession, text);
                }
                return true;
            case ColObject:
                if (m_impl->undoStack)
                {
                    const QString oldText = item->frameInfo->userObjectName;
                    if (oldText != text)
                    {
                        m_impl->undoStack->push(new SetFrameAttributesCommand(
                            m_impl->dataModel, FrameAttribute::UserObjectName, {{canonicalPath, oldText, text}}));
                    }
                }
                else
                {
                    m_impl->dataModel->updateFrameAttribute(canonicalPath, FrameAttribute::UserObjectName, text);
                }
                return true;
            case ColTag:
                if (m_impl->undoStack)
                {
                    const QString oldText = item->frameInfo->customTag;
                    if (oldText != text)
                    {
                        m_impl->undoStack->push(new SetFrameAttributesCommand(
                            m_impl->dataModel, FrameAttribute::CustomTag, {{canonicalPath, oldText, text}}));
                    }
                }
                else
                {
                    m_impl->dataModel->updateFrameAttribute(canonicalPath, FrameAttribute::CustomTag, text);
                }
                return true;
            default:
                break;
            }
        }
    }

    if (role == Qt::CheckStateRole)
    {
        TreeDisplayNode* item = static_cast<TreeDisplayNode*>(index.internalPointer());
        if (index.column() == ColName && item->type == TreeDisplayNode::Type::Frame && item->frameInfo.has_value())
        {
            const bool checked = (value.toInt() == Qt::Checked);
            const bool excluded = !checked;

            if (item->frameInfo->excluded != excluded)
            {
                const QString canonicalPath = item->frameInfo->id.canonicalPath();

                // Excluding a frame doesn't change its group key, so keep this model stable and just
                // update the affected nodes + backing model.
                m_impl->suppressNextFrameUpdated = true;
                m_impl->suppressNextFrameUpdatedPath = canonicalPath;
                m_impl->suppressNextGroupingChanged = true;
                m_impl->suppressNextCalibrationChanged = true;

                item->frameInfo->excluded = excluded;

                if (m_impl->dataModel)
                {
                    if (m_impl->undoStack)
                    {
                        m_impl->undoStack->push(new SetFrameAttributesCommand(
                            m_impl->dataModel, FrameAttribute::Excluded, {{canonicalPath, !excluded, excluded}}));
                    }
                    else
                    {
                        m_impl->dataModel->updateFrameAttribute(canonicalPath, FrameAttribute::Excluded, excluded);
                    }
                }

                if (m_impl->frameType == FrameType::Light)
                {
                    m_impl->invalidateWarningPaths();
                    m_impl->refreshWarningPathsIfNeeded();
                }

                const QModelIndex left = index.sibling(index.row(), 0);
                const QModelIndex right = index.sibling(index.row(), ColCount - 1);
                emit dataChanged(left, right,
                                 {Qt::CheckStateRole, Qt::DisplayRole, Qt::DecorationRole, Qt::ToolTipRole,
                                  Qt::ForegroundRole, Qt::BackgroundRole, Qt::FontRole});

                const QModelIndex groupIndex = parent(index);
                if (groupIndex.isValid())
                {
                    emit dataChanged(
                        groupIndex, groupIndex.sibling(groupIndex.row(), ColCount - 1),
                        {Qt::DisplayRole, Qt::ToolTipRole, Qt::ForegroundRole, Qt::BackgroundRole, Qt::FontRole});
                }
                return true;
            }
        }
    }
    return false;
}

