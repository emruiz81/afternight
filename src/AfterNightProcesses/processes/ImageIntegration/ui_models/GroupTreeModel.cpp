bool nodeHasWarning(const TreeDisplayNode* node, const QSet<QString>& warning_paths)
{
    if (!node)
    {
        return false;
    }
    if (node->type == TreeDisplayNode::Type::Frame && node->frameInfo.has_value())
    {
        return warning_paths.contains(node->frameInfo->id.canonicalPath());
    }
    for (const auto& child : node->children)
    {
        if (nodeHasWarning(child.get(), warning_paths))
        {
            return true;
        }
    }
    return false;
}

void countFramesRecursive(const TreeDisplayNode* node, int& included, int& excluded)
{
    if (!node)
    {
        return;
    }
    if (node->type == TreeDisplayNode::Type::Frame && node->frameInfo.has_value())
    {
        if (node->frameInfo->excluded)
        {
            ++excluded;
        }
        else
        {
            ++included;
        }
        return;
    }
    for (const auto& child : node->children)
    {
        countFramesRecursive(child.get(), included, excluded);
    }
}

/// Merge excluded frames back into the grouped view for UI display.
/// The processing pipeline grouping intentionally ignores excluded frames,
/// but the UI should show them (grayed/strikeout) in their logical groups.
GroupedFrameView mergeExcludedFrames(GroupedFrameView groups, const FrameCollection& collection, FrameType frameType,
                                     const GroupingOptions& options)
{
    GroupingEngine engine;
    const std::vector<FrameInfo> all_frames = collection.frames();
    for (const auto& frame : all_frames)
    {
        if (!frame.excluded)
        {
            continue;
        }

        GroupKey key = frame.manualGroupKey.has_value() ? frame.manualGroupKey.value()
                                                        : engine.computeGroupKey(frame, frameType, options);

        auto it =
            std::find_if(groups.begin(), groups.end(), [&key](const GroupedFrameSet& set) { return set.key == key; });
        if (it == groups.end())
        {
            groups.push_back(GroupedFrameSet{key, {}});
            it = std::prev(groups.end());
        }

        it->frames.push_back(frame);
    }

    // Keep deterministic ordering.
    for (auto& group : groups)
    {
        std::sort(group.frames.begin(), group.frames.end(),
                  [](const FrameInfo& lhs, const FrameInfo& rhs) { return lhs.id < rhs.id; });
    }
    std::sort(groups.begin(), groups.end(),
              [](const GroupedFrameSet& lhs, const GroupedFrameSet& rhs) { return lhs.key < rhs.key; });

    return groups;
}

/// Compute warning paths for light frames missing calibration matches.
/// Uses model's frame collections to detect user's intent (if they added bias/dark/flat
/// frames, they expect them to be used), then checks if each light has a match.
QSet<QString> computeWarningPaths(const IntegrationDataModel& dataModel)
{
    QSet<QString> result;

    const bool has_bias = !dataModel.biasFrames().empty();
    const bool has_dark = !dataModel.darkFrames().empty();
    const bool has_flat = !dataModel.flatFrames().empty();
    const bool hasCalibrationInputs = (has_bias || has_dark || has_flat);

    if (!hasCalibrationInputs)
    {
        return result;
    }

    CalibrationMatcher matcher(dataModel.groupingOptions(FrameType::Bias), dataModel.groupingOptions(FrameType::Dark),
                               dataModel.groupingOptions(FrameType::Flat), dataModel.calibrationMatchingPolicy());
    // These helpers live in CalibrationPanelUtils and already produce the same group view
    // as the Calibration tab.
    matcher.setBiasGroups(::collectBiasGroups(const_cast<IntegrationDataModel*>(&dataModel)));
    matcher.setDarkGroups(::collectDarkGroups(const_cast<IntegrationDataModel*>(&dataModel)));
    matcher.setFlatGroups(::collectFlatGroups(const_cast<IntegrationDataModel*>(&dataModel)));
    matcher.setOverrides(dataModel.calibrationOverrides());

    auto isUsableMatch = [](const CalibrationMatch& m) {
        return m.type != CalibrationMatch::MatchType::None && m.type != CalibrationMatch::MatchType::ManuallyUnassigned;
    };

    // Check each light group for missing calibration matches.
    // IMPORTANT: Respect the Pre-Calibrated flag by skipping entire light groups
    // that the user marked as already calibrated externally.
    const auto& settings_map = dataModel.lightCalibrationSettings();
    for (const auto& group : dataModel.lightGroups())
    {
        if (group.frames.empty())
        {
            continue;
        }

        const auto it = settings_map.find(group.key);
        if (it != settings_map.end() && it->second.preCalibrated)
        {
            continue;
        }

        const LightGroupKey lightKey = LightGroupKey::fromFrame(group.frames.front());

        const CalibrationMatch biasMatch = matcher.findBias(lightKey);
        const CalibrationMatch darkMatch = matcher.findDark(lightKey);
        const CalibrationMatch flatMatch = matcher.findFlat(lightKey);

        const bool bias_ok = has_bias ? isUsableMatch(biasMatch) : false;
        const bool dark_ok = has_dark ? isUsableMatch(darkMatch) : false;
        const bool flat_ok = has_flat ? isUsableMatch(flatMatch) : false;

        const bool bias_disabled = (biasMatch.type == CalibrationMatch::MatchType::ManuallyUnassigned);
        const bool dark_disabled = (darkMatch.type == CalibrationMatch::MatchType::ManuallyUnassigned);
        const bool flat_disabled = (flatMatch.type == CalibrationMatch::MatchType::ManuallyUnassigned);

        bool missing = false;

        // Same semantics as CalibrationCoverageWidget:
        // - When any calibration input exists, a group is "complete" only with a usable Flat
        //   match and either Bias or Dark (unless explicitly disabled).
        // - In CCD mode (subtractBiasFromDark), require both Bias and Dark (unless disabled).
        if (!flat_ok && !flat_disabled)
        {
            missing = true;
        }

        const bool bias_or_dark_ok = bias_ok || dark_ok;
        const bool bias_or_dark_disabled = bias_disabled || dark_disabled;
        if (!bias_or_dark_ok && !bias_or_dark_disabled)
        {
            missing = true;
        }

        const auto policy = dataModel.calibrationMatchingPolicy();
        if (policy.subtractBiasFromDark)
        {
            const bool bias_ok_or_disabled = bias_ok || bias_disabled;
            const bool dark_ok_or_disabled = dark_ok || dark_disabled;
            if (!(bias_ok_or_disabled && dark_ok_or_disabled))
            {
                missing = true;
            }
        }

        if (!missing)
        {
            continue;
        }

        for (const auto& frame : group.frames)
        {
            if (!frame.excluded)
            {
                result.insert(frame.id.canonicalPath());
            }
        }
    }

    return result;
}
