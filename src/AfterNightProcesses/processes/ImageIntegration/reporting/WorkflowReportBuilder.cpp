void WorkflowReportBuilder::appendPrintFooterContext(QString& md, const QDateTime& now) const
{
    const QString appVersion = resolveAppVersion(m_reportContext);
    const QString executionId =
        resolveContextValue(m_reportContext, QStringLiteral("executionId"), m_manifest.executionId);
    const QString generatedLocalRaw =
        resolveContextValue(m_reportContext, QStringLiteral("archivedAtLocal"), now.toString(Qt::ISODateWithMs));
    const QString generatedLocal = formatHumanDateTime(generatedLocalRaw, now);

    QStringList parts;
    parts << QStringLiteral("AfterNight %1").arg(appVersion);
    if (!executionId.trimmed().isEmpty())
    {
        parts << QStringLiteral("Execution %1").arg(executionId);
    }
    parts << QStringLiteral("Generated %1").arg(generatedLocal);

    md += QStringLiteral("<div class=\"an-print-footer\"><span class=\"an-print-footer-text\">%1</span></div>\n\n")
              .arg(parts.join(QStringLiteral(" \u2022 ")).toHtmlEscaped());
}

void WorkflowReportBuilder::appendSessionNotes(QString& md) const
{
    const QString outputDir = m_manifest.outputDirectory.trimmed();
    if (outputDir.isEmpty())
    {
        return;
    }

    const QString notesPath =
        QDir(outputDir).filePath(QStringLiteral(".afternight/image_integration/session_notes.txt"));
    QFile notesFile(notesPath);
    if (!notesFile.open(QIODevice::ReadOnly))
    {
        return;
    }

    const QString notes = QString::fromUtf8(notesFile.readAll()).trimmed();
    if (notes.isEmpty())
    {
        return;
    }

    const QFileInfo notesInfo(notesPath);
    md += QStringLiteral("## \U0001F4DD Session Notes\n\n");
    if (notesInfo.exists() && notesInfo.lastModified().isValid())
    {
        md += QStringLiteral("_Last updated: %1_\n\n")
                  .arg(notesInfo.lastModified().toLocalTime().toString(QStringLiteral("yyyy-MM-dd HH:mm:ss")));
    }

    md += QStringLiteral("<div class=\"an-session-notes\">%1</div>\n\n")
              .arg(notes.toHtmlEscaped().replace(QStringLiteral("\n"), QStringLiteral("<br/>")));
}

void WorkflowReportBuilder::appendQualityGate(QString& md) const
{
    appendSectionAnchor(md, QStringLiteral("quality-gate"));
    md += QStringLiteral("## \U0001F9ED Quality Gate\n");
    md += QStringLiteral("_Automated quality checks for quick go/no-go assessment of this execution._\n\n");
    md += QStringLiteral("_Interpretation: PASS/WARN/FAIL thresholds are heuristic defaults. ");
    md += QStringLiteral("Usable = Registered/Lights, Registration Success = Registered/Effective, ");
    md += QStringLiteral("and Exposure Completeness = frames with exposure metadata / total light frames._\n\n");
    md += QStringLiteral("| Criterion | Observed | Status |\n");
    md += QStringLiteral("|---|---|---|\n");

    const LogInputTotals logInputTotals = parseStackingInputTotalsFromLog(m_result.capturedLog);

    QString usableObserved = QStringLiteral("n/a (log input totals unavailable)");
    QualityGateState usableState = QualityGateState::Warn;
    if (logInputTotals.lights > 0)
    {
        const double usablePct =
            static_cast<double>(logInputTotals.registered) * 100.0 / static_cast<double>(logInputTotals.lights);
        usableObserved = QStringLiteral("%1 (%2/%3)")
                             .arg(formatPercent(usablePct))
                             .arg(logInputTotals.registered)
                             .arg(logInputTotals.lights);
        usableState = qualityGateStateFromPercent(usablePct, 80.0, 60.0);
    }
    md += QStringLiteral("| Usable Frames (Registered/Lights) | %1 | %2 |\n")
              .arg(usableObserved, qualityGateBadge(usableState));

    QString registrationObserved = QStringLiteral("n/a (effective frame totals unavailable)");
    QualityGateState registrationState = QualityGateState::Warn;
    if (logInputTotals.effective > 0)
    {
        const double registrationPct =
            static_cast<double>(logInputTotals.registered) * 100.0 / static_cast<double>(logInputTotals.effective);
        registrationObserved = QStringLiteral("%1 (%2/%3)")
                                   .arg(formatPercent(registrationPct))
                                   .arg(logInputTotals.registered)
                                   .arg(logInputTotals.effective);
        registrationState = qualityGateStateFromPercent(registrationPct, 90.0, 75.0);
    }
    md += QStringLiteral("| Registration Success (Registered/Effective) | %1 | %2 |\n")
              .arg(registrationObserved, qualityGateBadge(registrationState));

    int exposureTotalFrames = 0;
    int exposureKnownFrames = 0;
    for (const auto& group : m_manifest.integrationGroups)
    {
        const ExposureBreakdown breakdown = buildExposureBreakdown(group);
        exposureTotalFrames += breakdown.totalFrames;
        exposureKnownFrames += breakdown.knownFrames;
    }

    QString exposureObserved = QStringLiteral("n/a (no light frames)");
    QualityGateState exposureState = QualityGateState::Warn;
    if (exposureTotalFrames > 0)
    {
        const double exposurePct =
            static_cast<double>(exposureKnownFrames) * 100.0 / static_cast<double>(exposureTotalFrames);
        exposureObserved = QStringLiteral("%1 (%2/%3)")
                               .arg(formatPercent(exposurePct))
                               .arg(exposureKnownFrames)
                               .arg(exposureTotalFrames);
        exposureState = qualityGateStateFromPercent(exposurePct, 95.0, 80.0);
    }
    md += QStringLiteral("| Exposure Metadata Completeness | %1 | %2 |\n")
              .arg(exposureObserved, qualityGateBadge(exposureState));

    const bool hasFatalErrors = !m_result.errors.empty();
    QualityGateState fatalState = QualityGateState::Pass;
    QString fatalObserved = QStringLiteral("No fatal errors");
    if (hasFatalErrors)
    {
        fatalState = QualityGateState::Fail;
        fatalObserved = QStringLiteral("%1 reported error(s)").arg(m_result.errors.size());
    }
    else if (m_result.cancelled)
    {
        fatalState = QualityGateState::Warn;
        fatalObserved = QStringLiteral("Cancelled by user");
    }
    else if (!m_result.success)
    {
        fatalState = QualityGateState::Fail;
        fatalObserved = QStringLiteral("Run ended unsuccessfully");
    }
    md += QStringLiteral("| Fatal Errors | %1 | %2 |\n\n").arg(fatalObserved, qualityGateBadge(fatalState));
}

bool WorkflowReportBuilder::didStageRun(const QString& stageName) const
{
    for (const auto& stage : m_result.stageResults)
    {
        if (stage.stageName.compare(stageName, Qt::CaseInsensitive) == 0)
        {
            return true;
        }
    }
    return false;
}

int WorkflowReportBuilder::inferGroupCountForStage(const QString& stageName) const
{
    const QString lower = stageName.toLower();
    if (lower.contains(QStringLiteral("bias")))
    {
        return m_manifest.biasStage.has_value() ? static_cast<int>(m_manifest.biasStage->groups.size()) : 0;
    }
    if (lower.contains(QStringLiteral("dark")))
    {
        return m_manifest.darkStage.has_value() ? static_cast<int>(m_manifest.darkStage->groups.size()) : 0;
    }
    if (lower.contains(QStringLiteral("flat")))
    {
        return m_manifest.flatStage.has_value() ? static_cast<int>(m_manifest.flatStage->groups.size()) : 0;
    }
    if (lower.contains(QStringLiteral("registration")) || lower.contains(QStringLiteral("alignment")))
    {
        return static_cast<int>(m_manifest.registrationGroups.size());
    }
    // Normalization, Stacking, Drizzle, Calibration of lights — all operate on integration groups
    return static_cast<int>(m_manifest.integrationGroups.size());
}

QString WorkflowReportBuilder::resolvePathForRead(const QString& candidatePath) const
{
    const QString trimmed = candidatePath.trimmed();
    if (trimmed.isEmpty())
    {
        return {};
    }

    const QFileInfo info(trimmed);
    if (info.isAbsolute() || m_reportBaseDir.trimmed().isEmpty())
    {
        return trimmed;
    }

    return QDir(m_reportBaseDir).filePath(trimmed);
}

QString WorkflowReportBuilder::formatDuration(qint64 ms) const
{
    return formatWorkflowDuration(ms);
}

QString WorkflowReportBuilder::formatFileSize(qint64 bytes) const
{
    if (bytes < 1024)
        return QString::number(bytes) + " B";
    double kb = bytes / 1024.0;
    if (kb < 1024)
        return QString::number(kb, 'f', 1) + " KB";
    double mb = kb / 1024.0;
    if (mb < 1024)
        return QString::number(mb, 'f', 1) + " MB";
    double gb = mb / 1024.0;
    return QString::number(gb, 'f', 2) + " GB";
}

QString WorkflowReportBuilder::computeReproducibilityFingerprint(QString* manifestSettingsFingerprint,
                                                                 QString* inputFingerprint) const
{
    return ImageIntegration::Reporting::computeReproducibilityFingerprint(
        m_manifest, m_reportContext, manifestSettingsFingerprint, inputFingerprint);
}

