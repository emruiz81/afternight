// AfterNightEngine - hand-pruned median selection networks.
//
// Provenance: the four functions below are copied verbatim, apart from the namespace and the
// inlining macro. They are the scalar median networks for 9, 25, 49 and 81 values of RawTherapee's
// `median.h` (https://github.com/Beep6581/RawTherapee), as librtprocess carries it
// (https://github.com/CarVac/librtprocess) in a snapshot that states no version. That file states
// "Copyright (c) 2004-2010 Gabor Horvath <hgabor@rawtherapee.com>", attributes these median
// implementations to Flössie and Ingo Weyrich, and is licensed under the GNU General Public
// License, version 3 or (at your option) any later version; this file is a derived work distributed
// under that licence. The networks are upstream's; the namespace, the inlining macro and the
// caller's scan for non-finite samples are AfterNight's. The provenance note is
// `docs/dev/MEDIAN_NETWORKS_PROVENANCE.md`.
//
// Each function is a selection network: a fixed sequence of minimum and maximum operations, pruned
// by hand to the operations that can still reach the middle rank, so it returns the median of a
// complete 3x3, 5x5, 7x7 or 9x9 Float32 window without a branch. They remain the measured fast path
// for those four windows over an image in which every sample means something; the validity-aware
// general selector serves every other window, rank and rule. The sequences are the algorithm and
// are kept as written - there is nothing to factor out of them - which is why this private header
// is registered above the header-size ceiling with `OrderFilter.cpp` as its only consumer.
//
// Every input must be a number. A minimum or maximum involving a NaN depends on argument order, so
// a window holding one yields an order-dependent answer; the order filter scans the plane for a
// non-finite sample before it calls these.

